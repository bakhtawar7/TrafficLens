"""PostgreSQL backend for deployed TrafficLens run history.

The SQLite backend remains available for local development and path-based tests.
"""
from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from typing import Any

import psycopg2
from psycopg2.extras import RealDictCursor, Json

from . import config


class PostgresHistoryError(RuntimeError):
    """A readable error for PostgreSQL history failures."""


def _connect():
    if not config.DATABASE_URL:
        raise PostgresHistoryError("DATABASE_URL is not configured.")
    try:
        return psycopg2.connect(config.DATABASE_URL, cursor_factory=RealDictCursor)
    except psycopg2.Error as exc:
        raise PostgresHistoryError("Could not connect to the configured PostgreSQL database.") from exc


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def migrate() -> int:
    ddl = """
    CREATE TABLE IF NOT EXISTS schema_version (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS runs (
      id TEXT PRIMARY KEY, timestamp_utc TEXT NOT NULL, input_filename TEXT NOT NULL,
      image_sha256 TEXT NOT NULL, width INTEGER NOT NULL CHECK(width > 0),
      height INTEGER NOT NULL CHECK(height > 0), settings_sha256 TEXT NOT NULL,
      mode TEXT NOT NULL, selected_classes TEXT NOT NULL, threshold DOUBLE PRECISION NOT NULL,
      rickshaw_mode INTEGER NOT NULL CHECK(rickshaw_mode IN (0,1)),
      UNIQUE(image_sha256, settings_sha256, selected_classes, threshold, rickshaw_mode, mode)
    );
    CREATE TABLE IF NOT EXISTS model_results (
      run_id TEXT NOT NULL REFERENCES runs(id) ON DELETE CASCADE, model TEXT NOT NULL,
      weights_sha256 TEXT, total_count INTEGER NOT NULL CHECK(total_count >= 0),
      counts_by_class TEXT NOT NULL, inference_ms DOUBLE PRECISION NOT NULL CHECK(inference_ms >= 0),
      PRIMARY KEY(run_id, model)
    );
    CREATE TABLE IF NOT EXISTS reliability (
      run_id TEXT PRIMARY KEY REFERENCES runs(id) ON DELETE CASCADE,
      count_range_min INTEGER, count_range_max INTEGER, agreement_count DOUBLE PRECISION,
      agreement_box DOUBLE PRECISION, flag_status TEXT NOT NULL, flag_source TEXT,
      predicted_error DOUBLE PRECISION
    );
    CREATE TABLE IF NOT EXISTS corrections (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      run_id TEXT NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
      timestamp_utc TEXT NOT NULL, reviewer TEXT NOT NULL,
      corrected_counts TEXT NOT NULL, note TEXT NOT NULL DEFAULT ''
    );
    CREATE INDEX IF NOT EXISTS idx_runs_image_sha256 ON runs(image_sha256);
    CREATE INDEX IF NOT EXISTS idx_runs_timestamp_utc ON runs(timestamp_utc);
    """
    try:
        with _connect() as conn:
            with conn.cursor() as cur:
                cur.execute(ddl)
                cur.execute("SELECT COALESCE(MAX(version), 0) AS version FROM schema_version")
                version = int(cur.fetchone()["version"])
                if version > 1:
                    raise PostgresHistoryError(f"Database schema {version} is newer than supported schema 1.")
                if version == 0:
                    cur.execute("INSERT INTO schema_version(version, applied_at) VALUES (1, %s)", (_now(),))
        return 1
    except PostgresHistoryError:
        raise
    except psycopg2.Error as exc:
        raise PostgresHistoryError("Could not initialize the PostgreSQL history schema.") from exc


def record_run(run: dict[str, Any], model_results: list[dict[str, Any]],
               reliability_record: dict[str, Any] | None = None):
    from .history import RunWriteResult
    migrate()
    run_id = str(uuid.uuid4())
    selected = json.dumps(run["selected_classes"], separators=(",", ":"))
    key = (run["image_sha256"], run["settings_sha256"], selected,
           float(run["threshold"]), int(bool(run["rickshaw_mode"])), run["mode"])
    try:
        with _connect() as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    INSERT INTO runs(id,timestamp_utc,input_filename,image_sha256,width,height,
                    settings_sha256,mode,selected_classes,threshold,rickshaw_mode)
                    VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)
                    ON CONFLICT(image_sha256,settings_sha256,selected_classes,threshold,rickshaw_mode,mode)
                    DO NOTHING RETURNING id
                """, (run_id, run.get("timestamp_utc", _now()), run["input_filename"],
                      run["image_sha256"], int(run["width"]), int(run["height"]),
                      run["settings_sha256"], run["mode"], selected, float(run["threshold"]),
                      int(bool(run["rickshaw_mode"]))))
                inserted_row = cur.fetchone()
                inserted = inserted_row is not None
                if not inserted:
                    cur.execute("""SELECT id FROM runs WHERE image_sha256=%s AND settings_sha256=%s
                        AND selected_classes=%s AND threshold=%s AND rickshaw_mode=%s AND mode=%s""", key)
                    existing = cur.fetchone()
                    if existing is None:
                        raise PostgresHistoryError("Duplicate history run could not be located.")
                    run_id = existing["id"]
                for item in model_results:
                    cur.execute("""INSERT INTO model_results(run_id,model,weights_sha256,total_count,
                        counts_by_class,inference_ms) VALUES(%s,%s,%s,%s,%s,%s)
                        ON CONFLICT(run_id,model) DO NOTHING""",
                        (run_id, item["model"], item.get("weights_sha256"), int(item["total_count"]),
                         json.dumps(item["counts_by_class"], separators=(",", ":")), float(item["inference_ms"])))
                if reliability_record is not None:
                    cur.execute("""INSERT INTO reliability(run_id,count_range_min,count_range_max,
                        agreement_count,agreement_box,flag_status,flag_source,predicted_error)
                        VALUES(%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT(run_id) DO UPDATE SET
                        count_range_min=EXCLUDED.count_range_min,count_range_max=EXCLUDED.count_range_max,
                        agreement_count=EXCLUDED.agreement_count,agreement_box=EXCLUDED.agreement_box,
                        flag_status=EXCLUDED.flag_status,flag_source=EXCLUDED.flag_source,
                        predicted_error=EXCLUDED.predicted_error""",
                        (run_id, reliability_record.get("count_range_min"), reliability_record.get("count_range_max"),
                         reliability_record.get("agreement_count"), reliability_record.get("agreement_box"),
                         reliability_record.get("flag_status", "not validated"), reliability_record.get("flag_source"),
                         reliability_record.get("predicted_error")))
        return RunWriteResult(str(run_id), inserted)
    except (psycopg2.Error, KeyError, TypeError, ValueError) as exc:
        raise PostgresHistoryError("Run could not be saved to PostgreSQL history.") from exc


def list_runs(path=None, input_filter: str = "", model_filter: str = "") -> list[dict[str, Any]]:
    migrate()
    try:
        with _connect() as conn, conn.cursor() as cur:
            cur.execute("""SELECT r.*, l.count_range_min,l.count_range_max,l.agreement_count,
                l.agreement_box,l.flag_status,l.flag_source,l.predicted_error FROM runs r
                LEFT JOIN reliability l ON l.run_id=r.id WHERE r.input_filename ILIKE %s
                AND (%s='' OR EXISTS(SELECT 1 FROM model_results m WHERE m.run_id=r.id AND m.model ILIKE %s))
                ORDER BY r.timestamp_utc DESC,r.id DESC""",
                (f"%{input_filter}%", model_filter, f"%{model_filter}%"))
            return [dict(row) for row in cur.fetchall()]
    except psycopg2.Error as exc:
        raise PostgresHistoryError("History could not be read from PostgreSQL.") from exc


def get_run(run_id: str, path=None):
    run = next((r for r in list_runs(path) if r["id"] == run_id), None)
    if run is None:
        return None
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("SELECT * FROM model_results WHERE run_id=%s ORDER BY model", (run_id,))
        run["model_results"] = [dict(x) for x in cur.fetchall()]
        cur.execute("SELECT * FROM corrections WHERE run_id=%s ORDER BY id", (run_id,))
        run["corrections"] = [dict(x) for x in cur.fetchall()]
    return run


def delete_run(run_id: str, path=None):
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("DELETE FROM runs WHERE id=%s", (run_id,))


def clear_history(path=None):
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("DELETE FROM runs")


def export_rows(path=None):
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("""SELECT r.*,m.model,m.weights_sha256,m.total_count,m.counts_by_class,m.inference_ms,
            l.count_range_min,l.count_range_max,l.agreement_count,l.agreement_box,l.flag_status,l.flag_source,
            l.predicted_error FROM runs r LEFT JOIN model_results m ON m.run_id=r.id
            LEFT JOIN reliability l ON l.run_id=r.id ORDER BY r.timestamp_utc,r.id,m.model""")
        return [dict(x) for x in cur.fetchall()]


def _decode(value, fallback):
    if value is None:
        return fallback
    try:
        return json.loads(value)
    except (TypeError, json.JSONDecodeError) as exc:
        raise PostgresHistoryError("History contains invalid JSON.") from exc


def review_queue(path=None, filename_filter: str = "", queue_filter: str = "All"):
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("""SELECT r.id,r.timestamp_utc,r.input_filename,r.selected_classes,r.threshold,
            r.rickshaw_mode,l.flag_status,l.flag_source,l.count_range_min,l.count_range_max,
            l.agreement_count,l.agreement_box FROM runs r LEFT JOIN reliability l ON l.run_id=r.id
            WHERE r.input_filename ILIKE %s""", (f"%{filename_filter}%",))
        runs = [dict(x) for x in cur.fetchall()]
        for run in runs:
            cur.execute("SELECT model,total_count,counts_by_class FROM model_results WHERE run_id=%s ORDER BY model",
                        (run["id"],))
            run["model_results"] = [dict(x) for x in cur.fetchall()]
            cur.execute("""SELECT id,timestamp_utc,reviewer,corrected_counts,note FROM corrections
                WHERE run_id=%s ORDER BY id DESC LIMIT 1""", (run["id"],))
            latest = cur.fetchone()
            run["latest_correction"] = None if latest is None else {
                **dict(latest), "corrected_counts": _decode(latest["corrected_counts"], {})}
            run["selected_classes"] = _decode(run["selected_classes"], [])
            for item in run["model_results"]:
                item["counts_by_class"] = _decode(item["counts_by_class"], {})
    for run in runs:
        status = str(run.get("flag_status") or "not validated").casefold()
        run["queue_group"] = "flagged" if status in {"flagged","yes","needs review"} else "other"
        totals = [int(x["total_count"]) for x in run["model_results"]]
        run["disagreement_span"] = max(totals)-min(totals) if len(totals)>1 else 0
        run["review_order_label"] = "by model disagreement" if status in {"not validated","unvalidated",""} else "flagged first"
    runs.sort(key=lambda r:(r["queue_group"]!="flagged",
        -r["disagreement_span"] if r["review_order_label"]=="by model disagreement" else 0,
        r["timestamp_utc"],r["id"]))
    if queue_filter == "Unreviewed":
        runs = [r for r in runs if r["latest_correction"] is None]
    elif queue_filter == "Reviewed":
        runs = [r for r in runs if r["latest_correction"] is not None]
    return runs


def save_correction(run_id: str, corrected_counts: dict[str,int], reviewer: str,
                    note: str = "", path=None) -> int:
    expected = set(config.LABEL_CLASS_NAMES)
    if set(corrected_counts) != expected:
        raise ValueError("A correction must provide all seven project vehicle categories.")
    if any(isinstance(v,bool) or not isinstance(v,int) or v<0 for v in corrected_counts.values()):
        raise ValueError("Corrected counts must be non-negative whole numbers.")
    if not reviewer.strip():
        raise ValueError("Enter a reviewer name or anonymous reviewer label.")
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("""INSERT INTO corrections(run_id,timestamp_utc,reviewer,corrected_counts,note)
            VALUES(%s,%s,%s,%s,%s) RETURNING id""",
            (run_id,_now(),reviewer.strip(),json.dumps(corrected_counts,separators=(",",":"),sort_keys=True),note.strip()))
        return int(cur.fetchone()["id"])


def correction_export_rows(path=None):
    migrate()
    with _connect() as conn, conn.cursor() as cur:
        cur.execute("""SELECT c.id AS correction_id,c.run_id,c.timestamp_utc,c.reviewer,c.corrected_counts,
            c.note,r.input_filename,r.image_sha256,r.mode,r.rickshaw_mode,r.selected_classes
            FROM corrections c JOIN runs r ON r.id=c.run_id ORDER BY c.id""")
        rows = [dict(x) for x in cur.fetchall()]
    return [{**r,"corrected_counts":_decode(r["corrected_counts"],{}),
             "selected_classes":_decode(r["selected_classes"],[])} for r in rows]
